//Ternary operator
//It is a shorthand for if-else statement. It takes three operands: a condition, an expression to execute if the condition is true, and an expression to execute if the condition is false.

let age = 20;
let isAdult = (age >= 18) ? "You are an adult." : "You are not an adult.";
console.log(isAdult);

// Output: You are an adult.