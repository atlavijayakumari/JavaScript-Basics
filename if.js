//if example

let marks = 75;
if (marks >= 60) {
    console.log("You have passed the exam.");
}else if(marks >= 50) {
    console.log("You have scored average marks.");
}else if(marks >= 40) {
    console.log("You have scored below average marks.");
}else {
    console.log("You have failed the exam.");
}