console.log(10 == "10"); // true, because the values are equal
console.log(10 === "10"); // false, because the types are different
console.log(10 != "10"); // false, because the values are equal
console.log(10 !== "10"); // true, because the types are different
console.log(10 > 5); // true, because 10 is greater than 5
console.log(10 < 5); // false, because 10 is not less than 5
console.log(10 >= 10); // true, because 10 is equal to 10
console.log(10 <= 10); // true, because 10 is equal to 10