//Logical Operators in JavaScript

let age = 25;
let hasLicense = true;
//Logical and(&&) operator
console.log("Is age greater than 18 and has a license? " + (age >= 18 && hasLicense)); // true
//Logical or(||) operator
console.log("Is age greater than 18 or has a license? " + (age >= 18 || hasLicense)); // true
//Logical not(!) operator
console.log("Is age less than 18? " + !(age < 18)); // true
