//Loops
//A loop is used to execute a block of code repeatedly as long as a specified condition is true. 
//There are several types of loops in JavaScript, including for loops, while loops, and do-while loops.

//for loop
for(let i=0;i<3;i++){
    console.log(i);
}

let j = 0;

//while loop
while(j<3){
    console.log(j);
    j++;
}   

let k = 0;
//do-while loop
do{ 
    console.log(k);
    k++;
}while(k<3);