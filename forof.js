//for of loop is mainly used to get the values from an iterable such as an array, string, map, set, etc.
// It is a simpler and more readable way to iterate over the values of an iterable object compared to traditional for loops or while loops.

// Example 1: Using for of loop with an array
const fruits = ["apple", "banana", "cherry"];
for(let fruit of fruits){
    console.log(fruit);
}